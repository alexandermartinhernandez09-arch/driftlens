function profileLabel(t, profile) {
  const key = {
    auto: "profileAuto",
    general: "profileGeneral",
    human: "profileHuman",
    brand: "profileBrand",
    product: "profileProduct"
  }[profile] || "profileGeneral";
  return t[key];
}

function profileDisplayLabel(t, manual, detected) {
  if (!manual || manual === "auto") {
    return `${t.profileAuto} → ${profileLabel(t, detected)}`;
  }
  return profileLabel(t, manual);
}
